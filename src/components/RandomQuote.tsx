import React, { useEffect, useState } from 'react';

interface RandomQuoteProps {
  className?: string;
}

const RandomQuote: React.FC<RandomQuoteProps> = ({ className }) => {
  const [quote, setQuote] = useState<string>('');

  const quotes = [
    "Алматы - это когда утром гуляешь в горах, а вечером сидишь в модном баре.",
    "Город, где деревья старше большинства зданий.",
    "Алматы - город между снежными вершинами и пыльными равнинами.",
    "Здесь горы всегда на расстоянии вытянутой руки.",
    "Город тысячи красок и вкусов.",
    "Место, где каждая улица хранит свою историю.",
    "Алматы - душа Казахстана в объятиях Тянь-Шаня.",
    "Город контрастов, где современность встречается с традициями.",
    "Место, где всегда чувствуешь себя между Востоком и Западом.",
    "Город, который никогда не перестаёт удивлять.",
    "Яблоневый город у подножия гор.",
    "Здесь каждый район - это отдельная маленькая вселенная.",
    "Место, где время течёт иначе - неторопливо и со вкусом.",
    "Город, пропитанный ароматами цветущих садов и специй Востока.",
    "Алматы - это особое состояние души."
  ];

  useEffect(() => {
    // Выбираем случайную цитату при монтировании компонента
    const randomIndex = Math.floor(Math.random() * quotes.length);
    setQuote(quotes[randomIndex]);
  }, []);

  return (
    <div className={className}>
      <blockquote>
        <p>"{quote}"</p>
      </blockquote>
    </div>
  );
};

export default RandomQuote; 